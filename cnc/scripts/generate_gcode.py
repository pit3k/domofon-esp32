#!/usr/bin/env python3
"""Generate grblHAL G-code for the domofon-esp32 single-sided PCB.

Inputs : hardware/pcb/domofon.kicad_pcb  (B.Cu copper + Edge.Cuts, read with KiCad's pcbnew API)
         hardware/pcb/gerbers/domofon-PTH.drl, domofon-NPTH.drl (Excellon, mm)
Config : cnc/cam_config.toml
Output : cnc/gcode/NN_*.nc  (one tool per file, G21/G90, no M6, M3/M5/M30)

Coordinate system of the output (milled side = copper side = bottom of the board):
  board is viewed from the copper side -> mirrored in X:  x_m = W - x_kicad,  y_m = H - y_kicad
  X0 Y0 = lower-left corner of the board outline as seen by the operator, Z0 = copper surface.
pcb2gcode is not packaged in Debian 13, so this script does the same job with shapely.
"""
import math, os, re, sys, tomllib
from pathlib import Path
import pcbnew
from shapely.geometry import Polygon, MultiPolygon, LineString, Point, box
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[2]
PCB = ROOT / "hardware/pcb/domofon.kicad_pcb"
GERB = ROOT / "hardware/pcb/gerbers"
OUT = ROOT / "cnc/gcode"
CFG = tomllib.load(open(ROOT / "cnc/cam_config.toml", "rb"))

def poly_from_set(ps):
    polys = []
    for i in range(ps.OutlineCount()):
        o = ps.Outline(i)
        shell = [(o.CPoint(k).x / 1e6, o.CPoint(k).y / 1e6) for k in range(o.PointCount())]
        holes = []
        for h in range(ps.HoleCount(i)):
            hh = ps.Hole(i, h)
            holes.append([(hh.CPoint(k).x / 1e6, hh.CPoint(k).y / 1e6) for k in range(hh.PointCount())])
        polys.append(Polygon(shell, holes))
    return unary_union(polys)

def load_board():
    b = pcbnew.LoadBoard(str(PCB))
    lay = b.GetLayerID("B.Cu")
    items = []
    for t in b.GetTracks():
        if t.GetLayer() == lay:
            ps = pcbnew.SHAPE_POLY_SET()
            t.TransformShapeToPolygon(ps, lay, 0, 2000, pcbnew.ERROR_INSIDE)
            items.append(poly_from_set(ps))
    for p in b.GetPads():
        if p.IsOnLayer(lay) and p.GetAttribute() != pcbnew.PAD_ATTRIB_NPTH:  # NPTH pads carry no copper
            ps = pcbnew.SHAPE_POLY_SET()
            p.TransformShapeToPolygon(ps, lay, 0, 2000, pcbnew.ERROR_INSIDE)
            items.append(poly_from_set(ps))
    for z in b.Zones():
        if z.IsOnLayer(lay):
            items.append(poly_from_set(z.GetFilledPolysList(lay)))
    copper = unary_union(items)
    ol = pcbnew.SHAPE_POLY_SET()
    b.GetBoardPolygonOutlines(ol)
    outline = poly_from_set(ol)
    return copper, outline

def parse_excellon(path):
    tools, holes, cur = {}, [], None
    for line in open(path):
        line = line.strip()
        m = re.match(r"^T(\d+)C([\d.]+)", line)
        if m:
            tools[m.group(1)] = float(m.group(2)); continue
        m = re.match(r"^T(\d+)$", line)
        if m:
            cur = m.group(1); continue
        m = re.match(r"^X(-?[\d.]+)Y(-?[\d.]+)", line)
        if m and cur:
            holes.append((tools[cur], float(m.group(1)), -float(m.group(2))))  # Excellon Y is up -> kicad y down
    return holes

# ---------------------------------------------------------------- transforms
copper_k, outline_k = load_board()
minx, miny, maxx, maxy = outline_k.bounds          # outline incl. 0.05 line width? use exterior coords
W, H = maxx - minx, maxy - miny

def to_m(x, y):
    return (round(maxx - x, 4), round(maxy - y, 4))  # mirror X, flip Y-down -> Y-up, origin lower-left

def tf_geom(g):
    from shapely import affinity
    g = affinity.scale(g, xfact=-1, yfact=-1, origin=(0, 0))
    return affinity.translate(g, xoff=maxx, yoff=maxy)

copper = tf_geom(copper_k)
outline = tf_geom(outline_k)
holes = [(d,) + to_m(x, y) + ("PTH",) for d, x, y in parse_excellon(GERB / "domofon-PTH.drl")]
holes += [(d,) + to_m(x, y) + ("NPTH",) for d, x, y in parse_excellon(GERB / "domofon-NPTH.drl")]

# ---------------------------------------------------------------- gcode helpers
M = CFG["machine"]
def header(name, tool, rpm):
    return [f"( domofon-esp32 PCB - {name} )", f"( tool: {tool} )",
            f"( board {W:.2f} x {H:.2f} mm, copper side up, X0Y0 = lower-left board corner, Z0 = copper surface )",
            "( generated by cnc/scripts/generate_gcode.py from cnc/cam_config.toml )",
            "G21 G90 G94 G17", f"G0 Z{M['start_z']:.3f}", "G0 X0 Y0",
            f"M3 S{rpm}", f"G4 P{M['spindle_dwell_s']}"]
def footer():
    return [f"G0 Z{M['start_z']:.3f}", "M5", "G0 X0 Y0", "M30", ""]
def f(v): return f"{v:.4f}".rstrip("0").rstrip(".") if v != 0 else "0"

def nn_order(pts):
    pts = list(pts); out = []; cur = (0.0, 0.0)
    while pts:
        i = min(range(len(pts)), key=lambda k: (pts[k][0] - cur[0])**2 + (pts[k][1] - cur[1])**2)
        cur = pts.pop(i); out.append(cur)
    return out

def rings(g):
    if g.is_empty: return []
    gs = g.geoms if hasattr(g, "geoms") else [g]
    r = []
    for p in gs:
        r.append(list(p.exterior.coords)); r += [list(i.coords) for i in p.interiors]
    return r

def write(name, lines):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("\n".join(lines))
    print("wrote", name)

# ---------------------------------------------------------------- 01 isolation
I = CFG["isolation"]
groove = I["tip_mm"] + 2 * I["depth"] * math.tan(math.radians(I["angle_deg"] / 2))
step = groove * (1 - I["overlap"])
iso_offsets = [groove / 2 + I['safety'] + k * step for k in range(I["passes"])]
iso_paths = []
for off in iso_offsets:
    g = copper.buffer(off, quad_segs=16).simplify(0.005).boundary
    g = g.intersection(outline.buffer(0.3))  # clip: nothing beyond 0.3 mm outside the board edge
    gs = [] if g.is_empty else (list(g.geoms) if hasattr(g, "geoms") else [g])
    iso_paths += [list(l.coords) for l in gs if l.geom_type == "LineString" and l.length > 0.05]
lines = header("01 isolation", f"V-bit {I['angle_deg']:.0f} deg, tip {I['tip_mm']} mm, groove {groove:.3f} mm @ {I['depth']} mm", I["rpm"])
lines.insert(4, f"( isolation passes {I['passes']} at offsets {', '.join(f'{o:.3f}' for o in iso_offsets)} mm, overlap {I['overlap']*100:.0f} % )")
cur = (0, 0)
remaining = iso_paths[:]
while remaining:
    i = min(range(len(remaining)), key=lambda k: min((p[0]-cur[0])**2+(p[1]-cur[1])**2 for p in remaining[k]))
    r = remaining.pop(i)
    # start ring at closest vertex
    if r[0] == r[-1]:  # closed ring: start at the vertex closest to the tool
        r = r[:-1]
        j = min(range(len(r)), key=lambda k: (r[k][0]-cur[0])**2+(r[k][1]-cur[1])**2)
        r = r[j:] + r[:j] + [r[j]]
    elif (r[-1][0]-cur[0])**2+(r[-1][1]-cur[1])**2 < (r[0][0]-cur[0])**2+(r[0][1]-cur[1])**2:
        r = r[::-1]  # open path (clipped at the board edge): start at the nearer end
    lines += [f"G0 Z{M['safe_z']}", f"G0 X{f(r[0][0])} Y{f(r[0][1])}", f"G1 Z{f(-I['depth'])} F{I['plunge']}"]
    first = True
    for x, y in r[1:]:
        lines.append(f"G1 X{f(x)} Y{f(y)}" + (f" F{I['feed']}" if first else "")); first = False
    cur = r[-1]
lines += footer()
write("01_isolation_vbit30.nc", lines)

# ---------------------------------------------------------------- drills
D = CFG["drill"]; E = CFG["endmill"]
drill_sizes = sorted({h[0] for h in holes if h[0] < E["diameter"] + 0.6})  # 2.4 mm -> end mill
milled_holes = [h for h in holes if h[0] not in drill_sizes]
n = 2
for d in drill_sizes:
    pts = nn_order([(h[1], h[2]) for h in holes if h[0] == d])
    kinds = sorted({h[3] for h in holes if h[0] == d})
    name = f"{n:02d}_drill_{d:.1f}mm.nc"
    lines = header(f"{name[:-3]} ({len(pts)} holes, {'+'.join(kinds)})", f"drill bit {d:.1f} mm", D["rpm"])
    for x, y in pts:
        lines += [f"G0 X{f(x)} Y{f(y)}", f"G0 Z{f(D['retract'])}", f"G1 Z{f(D['depth'])} F{D['feed']}", f"G0 Z{f(D['retract'])}"]
    lines += footer()
    write(name, lines); n += 1

# ---------------------------------------------------------------- end mill: 2.4 holes + slot, then outline
r_t = E["diameter"] / 2
depths = []
z = 0.0
while z > E["total_depth"] + 1e-6:
    z = max(z - E["step_down"], E["total_depth"]); depths.append(round(z, 3))

lines = header(f"{n:02d} holes 2.4 mm + internal slot", f"flat end mill {E['diameter']} mm", E["rpm"])
for d, x, y, kind in milled_holes:
    rr = d / 2 - r_t
    lines += [f"( hole {d} mm {kind} at X{x} Y{y} - helical, circle r={rr:.3f} )",
              f"G0 Z{M['safe_z']}", f"G0 X{f(x + rr)} Y{f(y)}", f"G1 Z0.2 F{E['plunge']}"]
    zc = 0.2
    for zd in depths:  # one full helical turn per step, then a flat turn at the bottom
        lines.append(f"G2 X{f(x + rr)} Y{f(y)} I{f(-rr)} J0 Z{f(zd)} F{E['plunge'] * 2}")
    lines.append(f"G2 X{f(x + rr)} Y{f(y)} I{f(-rr)} J0 F{E['feed']}")
    lines.append(f"G0 Z{M['safe_z']}")
# internal slot(s) = interior rings of the board outline
inner = []
for p in (outline.geoms if hasattr(outline, "geoms") else [outline]):
    inner += [Polygon(i) for i in p.interiors]
slot_paths = []
for s in inner:
    path = s.buffer(-r_t, quad_segs=16)
    for r in rings(path):
        slot_paths.append(r)
        lines += ["( internal slot under U1/K1 )", f"G0 Z{M['safe_z']}", f"G0 X{f(r[0][0])} Y{f(r[0][1])}"]
        for zd in depths:
            lines.append(f"G1 Z{f(zd)} F{E['plunge']}")
            lines += [f"G1 X{f(x)} Y{f(y)} F{E['feed']}" for x, y in r[1:]]
        lines.append(f"G0 Z{M['safe_z']}")
lines += footer()
write(f"{n:02d}_mill_holes2.4_slot_endmill{E['diameter']:.1f}mm.nc", lines); n += 1

# outline with tabs
T = CFG["tabs"]
ext = Polygon(outline.exterior.coords) if not hasattr(outline, "geoms") else Polygon(outline.geoms[0].exterior.coords)
opath = ext.buffer(r_t, quad_segs=16).exterior
L = opath.length
# tabs in the middle of the 4 straight edges: pick positions along path closest to edge midpoints
bx0, by0, bx1, by1 = ext.bounds
mids = [((bx0+bx1)/2, by0), (bx1, (by0+by1)/2), ((bx0+bx1)/2, by1), (bx0, (by0+by1)/2)][:T["count"]]
tab_c = sorted(opath.project(Point(m)) for m in mids)
tab_half = (T["width"] + E["diameter"]) / 2
tab_z = round(-CFG["material"]["thickness"] + T["height"], 3)  # tab top, measured from copper surface
def in_tab(s): return any(abs(((s - c + L/2) % L) - L/2) < tab_half for c in tab_c)
# densify path
N = int(L / 0.2) + 1
pts = [opath.interpolate(i * L / N) for i in range(N + 1)]
lines = header(f"{n:02d} board outline with {T['count']} tabs", f"flat end mill {E['diameter']} mm (same as previous file)", E["rpm"])
lines.insert(4, f"( outline is cut OUTSIDE the board, tool centre offset {r_t} mm; tabs {T['width']} mm wide, {T['height']} mm thick at Z{tab_z} )")
lines += [f"G0 Z{M['safe_z']}", f"G0 X{f(pts[0].x)} Y{f(pts[0].y)}"]
outline_xyz = []
for zd in depths:
    lines.append(f"G1 Z{f(max(zd, tab_z) if in_tab(0) else zd)} F{E['plunge']}")
    first = True; last_z = None
    for i, p in enumerate(pts[1:], 1):
        s = i * L / N
        zz = max(zd, tab_z) if in_tab(s) else zd
        if zz != last_z and last_z is not None:
            lines.append(f"G1 Z{f(zz)} F{E['plunge']}")
        lines.append(f"G1 X{f(p.x)} Y{f(p.y)}" + (f" F{E['feed']}" if first or zz != last_z else ""))
        first = False; last_z = zz
        outline_xyz.append((p.x, p.y, zz))
lines += footer()
write(f"{n:02d}_outline_tabs_endmill{E['diameter']:.1f}mm.nc", lines)

# export geometry for verification
import pickle
pickle.dump(dict(copper=copper, outline=outline, holes=holes, iso_paths=iso_paths, groove=groove,
                 slot_paths=slot_paths, opath=opath, W=W, H=H, r_t=r_t, iso_offsets=iso_offsets),
            open("/tmp/cam_geom.pkl", "wb"))
print(f"board {W:.3f} x {H:.3f}, groove {groove:.3f}, offsets {iso_offsets}")
